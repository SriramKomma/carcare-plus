package ca.carcareplus.perf;

import java.time.LocalDate;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.Comparator;
import java.util.List;
import java.util.Map;
import java.util.Random;
import java.util.Set;
import java.util.TreeSet;
import java.util.function.Supplier;

import ca.carcareplus.models.ServiceDocument;
import ca.carcareplus.query.LevenshteinDistance;
import ca.carcareplus.query.SpellChecker;
import ca.carcareplus.query.SpellChecker.Suggestion;
import ca.carcareplus.query.Trie;
import ca.carcareplus.query.Trie.WordFrequency;
import ca.carcareplus.search.InvertedIndex;
import ca.carcareplus.search.TopK;
import ca.carcareplus.search.Tokenizer;

/**
 * Performance experiments for the report (plan section 12.5).
 *
 * Method for every measurement:
 * - System.nanoTime around the work;
 * - a few warm-up runs first, so the JIT compiler has optimised the code and we do
 *   not time the "cold start";
 * - then several timed runs, and the MEDIAN is reported (one slow run caused by
 *   garbage collection or another program does not distort the result).
 *
 * Every experiment first checks that both methods give the SAME answer; if not it
 * throws, so we can never compare a fast wrong method with a slow right one.
 *
 * All data is synthetic (see SyntheticData), not crawled.
 */
public final class Benchmarks {

    /** Sizes and repetitions. FULL is for the report; QUICK keeps unit tests fast. */
    public record Config(int warmups, int runs,
                         int[] indexSizes, int[] querySizes, int[] topKSizes,
                         int[] spellVocabularySizes, int[] completionVocabularySizes,
                         int bodyWords, int queries, int typos, int prefixes) {
    }

    public static final Config FULL = new Config(3, 5,
            new int[] {100, 500, 1_000, 5_000}, new int[] {1_000, 5_000}, new int[] {1_000, 10_000, 100_000},
            new int[] {1_000, 5_000, 20_000}, new int[] {1_000, 10_000, 50_000},
            200, 200, 20, 200);

    public static final Config QUICK = new Config(1, 1,
            new int[] {20}, new int[] {30}, new int[] {500},
            new int[] {300}, new int[] {300},
            30, 20, 5, 20);

    static final int K = 10;
    private static final long SEED = 2026;

    /** Results are added here so the JIT cannot decide the timed work is unused and skip it. */
    private static long sink;

    private Benchmarks() {
        // static helper methods only
    }

    /** The accumulated results (only read so the timed work cannot be optimised away). */
    static long sink() {
        return sink;
    }

    /** Runs every experiment and returns the results as Markdown. */
    public static String run(Config config) {
        StringBuilder md = new StringBuilder();
        md.append("# CarCare+ performance results\n\n")
                .append("Generated by `mvn -q compile exec:java -Dexec.args=\"benchmark\"` on ")
                .append(LocalDate.now()).append(".\n\n")
                .append("- Java ").append(Runtime.version()).append(", ")
                .append(System.getProperty("os.name")).append(' ').append(System.getProperty("os.arch"))
                .append(", ").append(Runtime.getRuntime().availableProcessors()).append(" processors\n")
                .append("- **Synthetic data** (made-up words and documents, fixed random seed), not crawled pages\n")
                .append("- Each time is the median of ").append(config.runs()).append(" runs after ")
                .append(config.warmups()).append(" warm-up runs (`System.nanoTime`)\n")
                .append("- Every row was checked: both methods returned the same answer\n\n");
        md.append(indexBuild(config));
        md.append(queryLookup(config));
        md.append(topK(config));
        md.append(spellCheck(config));
        md.append(completion(config));
        return md.toString();
    }

    // ---------------------------------------------------------- experiments

    /** E1: how index build time grows with the number of documents (expected: linear). */
    static String indexBuild(Config config) {
        StringBuilder md = table("1. Inverted index build time",
                "Documents | Words indexed | Build time (ms) | ms per 1,000 words",
                "Expected O(N) for N words: time per word should stay roughly constant.");
        List<String> vocabulary = SyntheticData.words(3_000, SEED);
        for (int size : config.indexSizes()) {
            List<ServiceDocument> docs = SyntheticData.documents(size, vocabulary, config.bodyWords(), SEED);
            long nanos = medianNanos(config, () -> InvertedIndex.of(docs).documentCount());
            long words = (long) size * (config.bodyWords() + 3);
            md.append(row(size, words, ms(nanos), String.format(java.util.Locale.ROOT, "%.4f", ms(nanos) * 1000.0 / words)));
        }
        return md.append('\n').toString();
    }

    /** E2: finding documents with a word, using the index vs scanning every document. */
    static String queryLookup(Config config) {
        StringBuilder md = table("2. Query: inverted index vs linear scan",
                "Documents | Queries | Index (µs per query) | Linear scan (µs per query) | Speed-up",
                "Linear scan uses already-tokenized documents (the fairest version of the scan). "
                        + "Index lookup is O(1) + O(p); the scan is O(N).");
        List<String> vocabulary = SyntheticData.words(3_000, SEED);
        Random random = new Random(SEED);
        for (int size : config.querySizes()) {
            List<ServiceDocument> docs = SyntheticData.documents(size, vocabulary, config.bodyWords(), SEED);
            InvertedIndex index = InvertedIndex.of(docs);
            List<List<String>> tokens = new ArrayList<>();
            for (ServiceDocument doc : docs) {
                tokens.add(Tokenizer.tokenize(doc.getTitle() + " " + doc.getBodyText()));
            }
            List<String> queries = new ArrayList<>();
            for (int i = 0; i < config.queries(); i++) {
                queries.add(vocabulary.get(random.nextInt(vocabulary.size())));
            }
            for (String q : queries) {
                check(index.lookup(q).equals(linearScan(tokens, q)), "index and scan differ for " + q);
            }
            long indexNanos = medianNanos(config, () -> {
                long found = 0;
                for (String q : queries) {
                    found += index.lookup(q).size();
                }
                return found;
            });
            long scanNanos = medianNanos(config, () -> {
                long found = 0;
                for (String q : queries) {
                    found += linearScan(tokens, q).size();
                }
                return found;
            });
            double indexMicros = indexNanos / 1000.0 / queries.size();
            double scanMicros = scanNanos / 1000.0 / queries.size();
            md.append(row(size, queries.size(), round(indexMicros), round(scanMicros), speedUp(scanNanos, indexNanos)));
        }
        return md.append('\n').toString();
    }

    /** E3: best 10 of n scores, min-heap vs sorting everything. */
    static String topK(Config config) {
        StringBuilder md = table("3. Top-" + K + " results: min-heap vs full sort",
                "Candidates (n) | Heap O(n log k) (ms) | Full sort O(n log n) (ms) | Speed-up",
                "The full sort copies the list first (sorting must not change the caller's list).");
        Comparator<Integer> biggestFirst = Comparator.reverseOrder();
        for (int size : config.topKSizes()) {
            Random random = new Random(SEED);
            List<Integer> scores = new ArrayList<>(size);
            for (int i = 0; i < size; i++) {
                scores.add(random.nextInt(1_000_000));
            }
            check(TopK.best(scores, K, biggestFirst).equals(fullSortTopK(scores, biggestFirst)), "top-k differs");
            long heapNanos = medianNanos(config, () -> TopK.best(scores, K, biggestFirst).get(0));
            long sortNanos = medianNanos(config, () -> fullSortTopK(scores, biggestFirst).get(0));
            md.append(row(size, ms(heapNanos), ms(sortNanos), speedUp(sortNanos, heapNanos)));
        }
        return md.append('\n').toString();
    }

    /** E4: spelling suggestions, full matrix for every word vs length filter + early exit. */
    static String spellCheck(Config config) {
        StringBuilder md = table("4. Spell check: brute force vs length filter + early exit",
                "Vocabulary words | Misspelled words | Brute force (ms per word) | Optimised (ms per word) | Speed-up",
                "Brute force fills the whole edit-distance table for every vocabulary word.");
        for (int size : config.spellVocabularySizes()) {
            List<String> vocabulary = SyntheticData.words(size, SEED);
            Map<String, Integer> frequencies = SyntheticData.frequencies(vocabulary);
            SpellChecker checker = new SpellChecker(frequencies);
            List<String> typos = SyntheticData.typos(vocabulary, config.typos(), SEED);
            for (String typo : typos) {
                check(checker.suggestions(typo, 2, 5).equals(bruteForceSuggestions(frequencies, typo, 2, 5)),
                        "spell check differs for " + typo);
            }
            long bruteNanos = medianNanos(config, () -> {
                long n = 0;
                for (String typo : typos) {
                    n += bruteForceSuggestions(frequencies, typo, 2, 5).size();
                }
                return n;
            });
            long fastNanos = medianNanos(config, () -> {
                long n = 0;
                for (String typo : typos) {
                    n += checker.suggestions(typo, 2, 5).size();
                }
                return n;
            });
            md.append(row(size, typos.size(), round(ms(bruteNanos) / typos.size()),
                    round(ms(fastNanos) / typos.size()), speedUp(bruteNanos, fastNanos)));
        }
        return md.append('\n').toString();
    }

    /** E5: word completion, Trie vs checking every vocabulary word. */
    static String completion(Config config) {
        StringBuilder md = table("5. Word completion: Trie vs linear scan of the vocabulary",
                "Vocabulary words | Prefixes | Trie (µs per prefix) | Linear scan (µs per prefix) | Speed-up",
                "Both return the " + K + " most frequent words with the prefix.");
        for (int size : config.completionVocabularySizes()) {
            List<String> vocabulary = SyntheticData.words(size, SEED);
            Map<String, Integer> frequencies = SyntheticData.frequencies(vocabulary);
            Trie trie = Trie.of(frequencies);
            List<String> prefixes = SyntheticData.prefixes(vocabulary, config.prefixes(), SEED);
            for (String prefix : prefixes) {
                check(trie.wordsWithPrefix(prefix, K).equals(linearCompletion(frequencies, prefix, K)),
                        "completion differs for " + prefix);
            }
            long trieNanos = medianNanos(config, () -> {
                long n = 0;
                for (String prefix : prefixes) {
                    n += trie.wordsWithPrefix(prefix, K).size();
                }
                return n;
            });
            long scanNanos = medianNanos(config, () -> {
                long n = 0;
                for (String prefix : prefixes) {
                    n += linearCompletion(frequencies, prefix, K).size();
                }
                return n;
            });
            md.append(row(size, prefixes.size(), round(trieNanos / 1000.0 / prefixes.size()),
                    round(scanNanos / 1000.0 / prefixes.size()), speedUp(scanNanos, trieNanos)));
        }
        return md.append('\n').toString();
    }

    // ------------------------------------------------- baselines (the "slow" way)

    /** Ids of documents whose tokens contain the term, by looking at every token. */
    static Set<Integer> linearScan(List<List<String>> tokensPerDoc, String term) {
        Set<Integer> result = new TreeSet<>();
        for (int id = 0; id < tokensPerDoc.size(); id++) {
            if (tokensPerDoc.get(id).contains(term)) {
                result.add(id);
            }
        }
        return result;
    }

    static List<Integer> fullSortTopK(List<Integer> scores, Comparator<Integer> order) {
        List<Integer> copy = new ArrayList<>(scores);
        copy.sort(order);
        return new ArrayList<>(copy.subList(0, Math.min(K, copy.size())));
    }

    /** Same ordering rules as SpellChecker, but the full table for every word. */
    static List<Suggestion> bruteForceSuggestions(Map<String, Integer> vocabulary, String word, int maxDistance, int k) {
        if (vocabulary.containsKey(word)) {
            return List.of();
        }
        List<Suggestion> found = new ArrayList<>();
        for (Map.Entry<String, Integer> entry : vocabulary.entrySet()) {
            int distance = LevenshteinDistance.distance(word, entry.getKey());
            if (distance <= maxDistance) {
                found.add(new Suggestion(entry.getKey(), distance, entry.getValue()));
            }
        }
        found.sort(Comparator.comparingInt(Suggestion::distance)
                .thenComparing(Comparator.comparingInt(Suggestion::frequency).reversed())
                .thenComparing(Suggestion::word));
        return new ArrayList<>(found.subList(0, Math.min(k, found.size())));
    }

    /** Same ordering rules as Trie.wordsWithPrefix, by checking every word. */
    static List<WordFrequency> linearCompletion(Map<String, Integer> vocabulary, String prefix, int k) {
        List<WordFrequency> found = new ArrayList<>();
        for (Map.Entry<String, Integer> entry : vocabulary.entrySet()) {
            if (entry.getKey().startsWith(prefix)) {
                found.add(new WordFrequency(entry.getKey(), entry.getValue()));
            }
        }
        found.sort(Comparator.comparingInt(WordFrequency::frequency).reversed().thenComparing(WordFrequency::word));
        return new ArrayList<>(found.subList(0, Math.min(k, found.size())));
    }

    // ---------------------------------------------------------------- helpers

    /** Runs the task warm-up times untimed, then runs times timed; returns the median in nanoseconds. */
    static long medianNanos(Config config, Supplier<?> task) {
        for (int i = 0; i < config.warmups(); i++) {
            sink += task.get().hashCode();
        }
        long[] times = new long[config.runs()];
        for (int i = 0; i < config.runs(); i++) {
            long start = System.nanoTime();
            Object result = task.get();
            times[i] = System.nanoTime() - start;
            sink += result.hashCode();
        }
        Arrays.sort(times);
        return times[times.length / 2];
    }

    private static void check(boolean same, String message) {
        if (!same) {
            throw new IllegalStateException("Benchmark methods disagree: " + message);
        }
    }

    private static StringBuilder table(String title, String header, String note) {
        StringBuilder md = new StringBuilder("## ").append(title).append("\n\n").append(note).append("\n\n");
        md.append("| ").append(header).append(" |\n|");
        md.append("---|".repeat(header.split("\\|").length)).append('\n');
        return md;
    }

    private static String row(Object... cells) {
        StringBuilder row = new StringBuilder("|");
        for (Object cell : cells) {
            row.append(' ').append(cell instanceof Double d ? round(d) : cell).append(" |");
        }
        return row.append('\n').toString();
    }

    private static double ms(long nanos) {
        return nanos / 1_000_000.0;
    }

    private static String round(double value) {
        return String.format(java.util.Locale.ROOT, value >= 100 ? "%.0f" : value >= 1 ? "%.2f" : "%.4f", value);
    }

    private static String speedUp(long slowNanos, long fastNanos) {
        return String.format(java.util.Locale.ROOT, "%.1fx", slowNanos / (double) Math.max(1, fastNanos));
    }
}
